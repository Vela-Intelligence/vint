// Explicit reproductions of the verified defects (assessment §6). Each is
// `test.fails`: it passes only while the defect is present, so the fix that
// lands in Phase 3 will fail these until they are promoted to `test`.
// ---------------------------------------------------------------------------

describe("known defects", () => {
  const liveFallbacks: Array<
    [string, (loading: Accessor<boolean>, text: Accessor<string>) => () => Child]
  > = [
    [
      "a Show",
      (loading) => () =>
        Show({ when: loading, children: () => li("spinner"), fallback: () => li("nothing") }),
    ],
    ["a bare accessor", (_, text) => () => text],
    ["an array with a function", (_, text) => () => [li("["), () => text(), li("]")]],
  ]

  for (const [what, fallback] of liveFallbacks) {
    test(`E47/C2 KNOWN(H3) a For fallback that is ${what} is removed entirely when rows appear`, () => {
      const [items, setItems] = createSignal<string[]>([])
      const [loading] = createSignal(false)
      const [text] = createSignal("nothing")
      mount(host, () =>
        ul(For({ each: items, fallback: fallback(loading, text), children: (i) => li(() => i()) })),
      )
      expect(host.textContent).toBe(what === "an array with a function" ? "[nothing]" : "nothing")
      setItems(["a"])
      // C2: "everything it renders — including content that arrives on a
      // later flush — is removed when the list becomes non-empty"
      expect(host.textContent).toBe("a")
      expect(host.querySelectorAll("li")).toHaveLength(1)
    })
  }

  test("E48/D9 KNOWN(H3) a top-level For with a Show fallback: dispose removes the orphan too", () => {
    const [items, setItems] = createSignal<string[]>([])
    const [loading] = createSignal(false)
    const dispose = mount(host, () =>
      For({
        each: items,
        fallback: () =>
          Show({ when: loading, children: () => li("spinner"), fallback: () => li("nothing") }),
        children: (i) => li(() => i()),
      }),
    )
    setItems(["a"])
    setItems([])
    setItems(["b"])
    dispose()
    // D9: "removes the mounted DOM" is literal
    expect(host.childNodes.length).toBe(0)
  })

  test("E49/D9 KNOWN(M1) a view whose binding throws on its first run leaves nothing subscribed", () => {
    const [n] = createSignal(0)
    expect(() =>
      mount(host, () =>
        div({
          class: () => {
            n() // tracked before the throw
            throw new Error("boom")
          },
        }),
      ),
    ).toThrow("boom")
    // D9: "mount disposes the root, removes anything it appended, and
    // rethrows — nothing stays subscribed"
    expect(__observerCount(n)).toBe(0)
    expect(host.childNodes.length).toBe(0)
  })

  test("E50/D2 KNOWN(L8) a For created outside a binding and returned twice survives the second run", () => {
    const [tick, setTick] = createSignal(0)
    const [list] = createSignal([1, 2])
    mount(host, () => {
      const frag = For({ each: list, children: (item) => span(() => String(item())) })
      return div(() => {
        tick() // an unrelated dependency re-runs the binding
        return frag
      })
    })
    expect(host.textContent).toBe("12")
    setTick(1)
    // D2: "a fragment that an earlier run of the same binding already
    // expanded re-expands to the same nodes when returned again"
    expect(host.textContent).toBe("12")
  })
})
